/** Normalises a country code as read ("ca", " CA ") to upper case, or null when it is not one. */
export function countryCode(raw: unknown): string | null {
  if (typeof raw !== 'string') return null;
  const code = raw.trim().toUpperCase();
  return /^[A-Z]{2}$/.test(code) ? code : null;
}

/** The currency a country bills in, or null when the table names none for it. */
export function currencyForCountry(country: unknown): MinorUnitCurrency | null {
  const code = countryCode(country);
  if (code === null || !Object.hasOwn(COUNTRY_CURRENCY, code)) return null;
  return COUNTRY_CURRENCY[code] ?? null;
}
