// Writes src/migrations.ts from migrations/NNNN_name.sql. The SQL files are the versioned source
// (S§4); embedding them as a module lets the bundled server (apps/server, tsdown) carry them with no
// file beside dist/. test/migrate.test.ts fails when the module and the files disagree.
// Run: pnpm --filter @agentic-dasher/db migrations:embed
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const folder = join(root, 'migrations');

const files = readdirSync(folder)
  .filter((f) => f.endsWith('.sql'))
  .sort();

const entries = files.map((file, i) => {
  const version = i + 1;
  const prefix = String(version).padStart(4, '0');
  if (!new RegExp(`^${prefix}_[a-z0-9_]+\\.sql$`).test(file)) {
    throw new Error(`${file}: expected ${prefix}_<name>.sql (numbered from 0001, no gaps)`);
  }
  const text = readFileSync(join(folder, file), 'utf8');
  const literal = text.replaceAll('\\', '\\\\').replaceAll('`', '\\`').replaceAll('${', '\\${');
  return `  {\n    version: ${version},\n    name: '${file.slice(0, -'.sql'.length)}',\n    sql: \`${literal}\`,\n  },\n`;
});

const header = `// Generated by scripts/embed-migrations.ts from migrations/*.sql. Do not edit: change the SQL
// files (a released one never changes) and run \`pnpm --filter @agentic-dasher/db migrations:embed\`.
import type { Migration } from './migrate.ts';

export const MIGRATIONS: readonly Migration[] = [
`;

writeFileSync(join(root, 'src', 'migrations.ts'), `${header}${entries.join('')}];\n`);
