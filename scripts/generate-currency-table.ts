// Generates packages/shared/src/currency-table.ts from ISO 4217 List One (S§2.2).
// Usage: node scripts/generate-currency-table.ts <list-one.xml> [--allow-exponent-change]
// Download the list first, e.g. `curl -fsSLo list-one.xml <SOURCE_URL below>`.
//
// Guard for stored data: amounts are stored as minor units without their exponent and
// price_observation is append-only, so changing an existing code's exponent or dropping a code
// would silently rescale or orphan stored prices. The script compares the list with the committed
// table and refuses both (exit 1, nothing written) unless --allow-exponent-change is passed.

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { ISO_MINOR_UNITS as CURRENT } from '../packages/shared/src/currency-table.ts';

interface Entry {
  minor: number | null;
  fund: boolean;
  name: string;
}

const SOURCE_URL =
  'https://www.six-group.com/dam/download/financial-information/data-center/iso-currrency/lists/list-one.xml';
const OUT = new URL('../packages/shared/src/currency-table.ts', import.meta.url);
const ALLOW_FLAG = '--allow-exponent-change';

const args = process.argv.slice(2);
const allowChange = args.includes(ALLOW_FLAG);
const [xmlPath, ...extra] = args.filter((a) => a !== ALLOW_FLAG);
if (!xmlPath || extra.length > 0) {
  console.error(`usage: node scripts/generate-currency-table.ts <list-one.xml> [${ALLOW_FLAG}]`);
  process.exit(2);
}

const bytes = readFileSync(xmlPath);
const xml = bytes.toString('utf8');
const sha256 = createHash('sha256').update(bytes).digest('hex');
const published = /<ISO_4217 Pblshd="(\d{4}-\d{2}-\d{2})">/.exec(xml)?.[1];
if (!published) throw new Error('no Pblshd date: is this ISO 4217 List One?');

function decode(text: string): string {
  return text
    .replaceAll('&apos;', "'")
    .replaceAll('&quot;', '"')
    .replaceAll('&lt;', '<')
    .replaceAll('&gt;', '>')
    .replaceAll('&amp;', '&');
}

function tag(entry: string, name: string): { attrs: string; text: string } | undefined {
  const m = new RegExp(`<${name}( [^>]*)?>([^<]*)</${name}>`).exec(entry);
  return m ? { attrs: m[1] ?? '', text: decode(m[2] ?? '').trim() } : undefined;
}

const codes = new Map<string, Entry>();
for (const [, entry = ''] of xml.matchAll(/<CcyNtry>([\s\S]*?)<\/CcyNtry>/g)) {
  const code = tag(entry, 'Ccy')?.text;
  if (code === undefined) continue; // "No universal currency" rows carry no code.
  const name = tag(entry, 'CcyNm');
  const units = tag(entry, 'CcyMnrUnts')?.text;
  if (!/^[A-Z]{3}$/.test(code) || !name || units === undefined) {
    throw new Error(`unexpected entry for ${code}`);
  }
  if (units !== 'N.A.' && !/^\d$/.test(units)) throw new Error(`bad minor unit ${units} (${code})`);
  const next: Entry = {
    minor: units === 'N.A.' ? null : Number(units),
    fund: /IsFund="true"/.test(name.attrs),
    name: name.text,
  };
  const prev = codes.get(code);
  if (prev && (prev.minor !== next.minor || prev.fund !== next.fund)) {
    throw new Error(`inconsistent entries for ${code}`);
  }
  if (!prev) codes.set(code, next);
}
const sorted = [...codes.keys()].sort();

const violations: string[] = [];
for (const [code, minor] of Object.entries(CURRENT)) {
  const entry = codes.get(code);
  if (!entry) violations.push(`${code} would be dropped`);
  else if (entry.minor !== minor) violations.push(`${code} exponent ${minor} -> ${entry.minor}`);
}
if (violations.length > 0 && !allowChange) {
  console.error(
    [
      'Refusing to write the currency table. Stored amounts are minor units without their',
      'exponent, so these changes would rescale or orphan stored prices:',
      ...violations.map((v) => `  ${v}`),
      `Migrate stored amounts first, then re-run with ${ALLOW_FLAG}.`,
    ].join('\n'),
  );
  process.exit(1);
}

const minorOf = (code: string) => codes.get(code)?.minor ?? null;
const out = [
  '// GENERATED by scripts/generate-currency-table.ts. Do not edit by hand.',
  '//',
  '// Source: ISO 4217 List One, "Current currency & funds code list", published by the ISO 4217',
  '// maintenance agency (SIX Financial Information) as XML.',
  `//   URL:       ${SOURCE_URL}`,
  `//   Published: ${published} (the list's Pblshd attribute)`,
  `//   SHA-256:   ${sha256}`,
  '//',
  '// Every distinct alphabetic code in the list, sorted. Minor units are copied as published;',
  '// "N.A." (no minor unit: precious metals, bond-market units, SDR, XSU, XUA, XTS, XXX) is',
  '// `null`. Fund codes (`IsFund="true"`) are kept, with their published minor units. Rows with',
  '// no code ("No universal currency") are skipped.',
  '//',
  '// Exponent stability: amounts are stored as integer minor units without their exponent, and',
  "// price_observation is append-only. Changing an existing code's exponent or dropping a code",
  '// would silently rescale or orphan stored prices, so the generator refuses both unless it is',
  '// run with --allow-exponent-change, after the stored amounts have been migrated.',
  '//',
  '// To refresh: download the list, run `node scripts/generate-currency-table.ts <list-one.xml>`,',
  '// then re-review packages/shared/test/currency.test.ts.',
  '',
  'export const ISO_4217_LIST_ONE = {',
  `  url: '${SOURCE_URL}',`,
  `  published: '${published}',`,
  `  sha256: '${sha256}',`,
  '} as const;',
  '',
  '/** Every active ISO 4217 alphabetic code, sorted. */',
  'export const ISO_CURRENCY_CODES = [',
  ...sorted.map((c) => `  '${c}',`),
  '] as const;',
  '',
  '/** ISO 4217 minor units per code; `null` where the list says "N.A.". */',
  'export const ISO_MINOR_UNITS = {',
  ...sorted.map((c) => {
    const entry = codes.get(c);
    return `  ${c}: ${minorOf(c)}, // ${entry?.name}${entry?.fund ? ' (fund)' : ''}`;
  }),
  '} as const satisfies Record<(typeof ISO_CURRENCY_CODES)[number], number | null>;',
  '',
  '/** Codes the list marks as funds (`IsFund="true"`). */',
  'export const ISO_FUND_CODES = [',
  ...sorted.filter((c) => codes.get(c)?.fund).map((c) => `  '${c}',`),
  '] as const;',
  '',
];
writeFileSync(OUT, out.join('\n'));
console.info(`wrote ${sorted.length} codes, published ${published}, sha256 ${sha256}`);
